
import json
from pathlib import Path
from collections import Counter
import pandas as pd

BASE = Path(__file__).resolve().parent
OUTPUT = BASE / "outputs"

def load_json(filename):
    with open(OUTPUT / filename, "r", encoding="utf-8") as f:
        return json.load(f)

claims_data = load_json("extracted_claims.json")
a_data = load_json("experiment_A_direct.json")
b_data = load_json("experiment_B_criteria.json")

# Index extracted claims by case and claim ID
claims = {}
for record in claims_data:
    for claim in record["claims"]:
        key = (record["case_id"], claim["claim_id"])

        # Handle inconsistent field names generated by the LLM
        claim_text = next(
            (
                value
                for field, value in claim.items()
                if field.startswith("claim") and isinstance(value, str)
            ),
            ""
        )

        if not claim_text:
            print("WARNING: Missing claim text:", key, claim)

        claims[key] = claim_text

# Index experiment evaluations by case and claim ID

def index_evaluations(data, experiment_name):
    indexed = {}

    for record in data:
        case_id = record["case_id"]

        # Get the corresponding extracted claims
        extracted = next(
            r for r in claims_data
            if r["case_id"] == case_id
        )["claims"]

        for position, evaluation in enumerate(record["evaluations"]):

            # First try the normal claim_id
            claim_id = evaluation.get("claim_id")

            # Recover missing IDs using the original claim order
            if claim_id is None:
                if position < len(extracted):
                    claim_id = extracted[position]["claim_id"]
                    print(
                        f"WARNING: Recovered missing claim_id "
                        f"for {experiment_name}, {case_id}, "
                        f"claim {claim_id}"
                    )
                else:
                    print(
                        f"ERROR: Cannot recover claim_id for "
                        f"{experiment_name}, {case_id}, position {position}"
                    )
                    continue

            key = (case_id, claim_id)

            if key in indexed:
                raise ValueError(
                    f"Duplicate evaluation: {experiment_name}, {key}"
                )

            indexed[key] = evaluation

    return indexed


a_index = index_evaluations(a_data, "Experiment A")
b_index = index_evaluations(b_data, "Experiment B")

a_keys = set(a_index)
b_keys = set(b_index)
common_keys = sorted(a_keys & b_keys)

print("\n========== PAIRING VALIDATION ==========")
print("Extracted claims:", len(claims))
print("A evaluations:", len(a_index))
print("B evaluations:", len(b_index))
print("Matched A/B pairs:", len(common_keys))
print("Missing from A:", len(b_keys - a_keys))
print("Missing from B:", len(a_keys - b_keys))

if not common_keys:
    raise ValueError("No matching claim evaluations found.")

# Prepare paired comparison
rows = []

for key in common_keys:
    case_id, claim_id = key
    a = a_index[key]
    b = b_index[key]

    rows.append({
        "case_id": case_id,
        "claim_id": claim_id,
        "claim": claims.get(key, a.get("claim", "")),
        "A_label": a.get("label", ""),
        "B_label": b.get("label", ""),
        "A_evidence": a.get("evidence", ""),
        "B_evidence": b.get("evidence", ""),
        "A_reason": a.get("reason", ""),
        "B_reason": b.get("reason", ""),
        "B_evidence_assessment": b.get("evidence_assessment", "")
    })

df = pd.DataFrame(rows)

# Label order
labels = [
    "Supported",
    "Contradicted",
    "Not Supported",
    "Unverifiable"
]

# Confusion matrix
matrix = pd.crosstab(
    df["A_label"],
    df["B_label"]
).reindex(index=labels, columns=labels, fill_value=0)

print("\n========== CONFUSION MATRIX ==========")
print("Rows = Experiment A; Columns = Experiment B")
print(matrix)

# Exact agreement
n = len(df)
agreements = (df["A_label"] == df["B_label"]).sum()
observed_agreement = agreements / n

# Cohen's kappa
count_a = Counter(df["A_label"])
count_b = Counter(df["B_label"])

expected_agreement = sum(
    count_a[label] * count_b[label] for label in labels
) / (n * n)

if expected_agreement == 1:
    kappa = float("nan")
else:
    kappa = (
        observed_agreement - expected_agreement
    ) / (1 - expected_agreement)

print("\n========== AGREEMENT RESULTS ==========")
print("Matched pairs:", n)
print("Exact agreements:", agreements)
print("Disagreements:", n - agreements)
print(f"Exact agreement: {observed_agreement:.4f} ({observed_agreement*100:.2f}%)")
print(f"Cohen's kappa: {kappa:.4f}")

# Label distribution
print("\n========== LABEL DISTRIBUTIONS ==========")
print("A:", Counter(df["A_label"]))
print("B:", Counter(df["B_label"]))

# Save all paired results
df.to_csv(
    OUTPUT / "paired_prompt_comparison.csv",
    index=False,
    encoding="utf-8-sig"
)

# Save disagreements separately for manual qualitative review
disagreements = df[df["A_label"] != df["B_label"]].copy()

disagreements.to_csv(
    OUTPUT / "prompt_disagreements.csv",
    index=False,
    encoding="utf-8-sig"
)

print("\n========== OUTPUT FILES ==========")
print("Paired comparison:", OUTPUT / "paired_prompt_comparison.csv")
print("Disagreements:", OUTPUT / "prompt_disagreements.csv")
print("\nAnalysis completed successfully.")
